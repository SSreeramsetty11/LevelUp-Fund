-- Apply after the existing shared-admin and age-confirmation migrations.
-- Stage 1: add income support without breaking the existing test form.
-- During this stage, old clients can still omit income. Apply stage 2 after
-- deploying the updated form and keep the site in test mode throughout.
begin;
alter table public.levelup_applications
  add column if not exists household_income numeric(12,2)
  check (household_income is null or (household_income >= 0 and household_income <> 'NaN'::numeric));

grant insert (household_income) on public.levelup_applications to anon, authenticated;

create or replace function public.levelup_enforce_income_rules()
returns trigger language plpgsql set search_path = '' as $$
begin
  if new.amount is null or new.amount = 'NaN'::numeric or new.amount <= 0 then
    raise exception 'The requested amount must be a valid positive amount.';
  end if;
  if tg_op = 'INSERT' then
    if new.household_income is null then
      -- Temporary compatibility with the existing test form; stage 2 blocks this.
      new.status := 'Pending';
      return new;
    end if;
    -- The applicant cannot set status through the public insert grant.
    if new.household_income > 90000 then
      new.status := 'Rejected';
    else
      new.status := 'Pending';
    end if;
    return new;
  end if;

  -- Ineligible high-income submissions cannot be returned to a non-rejected state.
  if new.household_income > 90000 and new.status <> 'Rejected' then
    raise exception 'Applications with annual household income over $90,000 must remain rejected.';
  end if;

  if new.status = 'Approved' then
    if new.household_income is null then
      -- Preserve and permit ordinary edits to approvals made before this policy.
      if old.status is distinct from 'Approved' or old.household_income is not null or new.amount is distinct from old.amount then
        raise exception 'Annual household income is required before approval.';
      end if;
    elsif new.amount * 10000 <= new.household_income * 75 then
      raise exception 'The requested amount must exceed 0.75 percent of annual household income.';
    end if;
  end if;
  return new;
end;
$$;
revoke all on function public.levelup_enforce_income_rules() from public;

drop trigger if exists levelup_income_rules on public.levelup_applications;
create trigger levelup_income_rules before insert or update of status, amount, household_income
  on public.levelup_applications for each row execute function public.levelup_enforce_income_rules();

-- RLS runs after the BEFORE trigger, so the policy permits only the status
-- generated by the trigger. Existing column grants prevent clients setting status.
drop policy if exists application_submit on public.levelup_applications;
create policy application_submit on public.levelup_applications
  for insert to anon, authenticated
  with check (
    age_confirmed is true
    and status = case when household_income > 90000 then 'Rejected' else 'Pending' end
    and practice_score is null and notes = ''
  );
commit;
